package mini

import (
	"go.uber.org/dig"

	"github.com/cjdias/flam-in-go/pkg/flam"
	"github.com/cjdias/flam-in-go/pkg/flam/bundle"
	"github.com/cjdias/flam-in-go/pkg/flam/redis"
)

// NewBundle returns the [flam.IBundle] of the mini connection driver,
// providing its [flam.IRedisConnectionCreator] in the
// [redis.ConnectionCreatorGroup] group. It is also a
// [flam.IConfigurableBundle], setting the default of the address at
// [DefaultAddressConfigPath]. It configures no connection.
func NewBundle() flam.IBundle {
	return &bundleImpl{}
}

// bundleImpl is the [flam.IBundle] returned by [NewBundle].
type bundleImpl struct{}

// compile time check that *bundleImpl implements IConfigurableBundle
var _ flam.IConfigurableBundle = (*bundleImpl)(nil)

func (b *bundleImpl) Id() string {
	return bundleId
}

func (b *bundleImpl) Config(
	bag flam.IBag,
) error {
	return bag.Set(DefaultAddressConfigPath, defaultAddress)
}

func (b *bundleImpl) Register(
	app flam.IApp,
) error {
	return bundle.NewRegisterer(app).
		QueueProvider(newCreator, dig.Group(redis.ConnectionCreatorGroup)).
		Register()
}
