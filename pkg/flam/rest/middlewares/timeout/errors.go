package timeout

import (
	"errors"

	"github.com/cjdias/flam-in-go/pkg/flam"
)

var (
	// ErrInvalidField is the error wrapped by the error returned from the
	// creator when a field of the middleware configuration, or its
	// default, does not hold a value of the expected type: a timeout
	// duration of more than 0.
	ErrInvalidField = errors.New("invalid timeout rest middleware field")

	// ErrTimeout is the error of the 503 envelope answering a request
	// whose context is done before its handler returns.
	ErrTimeout = errors.New("request timed out")
)

// newErrCreate returns the error wrapping the sentinel with the message and
// the ErrorFieldID and ErrorFieldField context fields.
func newErrCreate(
	sentinel error,
	message string,
	id string,
	field string,
) *flam.Error {
	return flam.NewWrappedError(sentinel, message).
		With(ErrorFieldID, id).
		With(ErrorFieldField, field)
}
