package spanish

import (
	"go.uber.org/dig"

	"github.com/cjdias/flam-in-go/pkg/flam"
	"github.com/cjdias/flam-in-go/pkg/flam/bundle"
	"github.com/cjdias/flam-in-go/pkg/flam/container"
	"github.com/cjdias/flam-in-go/pkg/flam/factory"
	"github.com/cjdias/flam-in-go/pkg/flam/translator"
)

// NewBundle returns the [flam.IBundle] of the Spanish translator driver,
// providing its [flam.ITranslatorCreator] in the
// [translator.CreatorGroup] group. It is also a
// [flam.IConfigurableBundle], configuring by default a translator of id
// [Id] with this driver, holding no text.
func NewBundle() flam.IBundle {
	return &bundleImpl{}
}

// bundleImpl is the [flam.IBundle] returned by [NewBundle].
type bundleImpl struct{}

// compile time check that *bundleImpl implements IConfigurableBundle
var _ flam.IConfigurableBundle = (*bundleImpl)(nil)

func (b *bundleImpl) Id() string {
	return bundleId
}

func (b *bundleImpl) Config(
	bag flam.IBag,
) error {
	return bag.Set(translator.ConfigPath+"."+Id, container.Bag{
		factory.ConfigFieldDriver: Driver,
	})
}

func (b *bundleImpl) Register(
	app flam.IApp,
) error {
	return bundle.NewRegisterer(app).
		QueueProvider(newCreator, dig.Group(translator.CreatorGroup)).
		Register()
}
